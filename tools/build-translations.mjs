// Regenerates translations/translations.bundle.js from translations/ar.json and en.json.
// The bundle lets the site run when opened directly from disk (file://), where
// browsers block fetch() of local JSON files. The JSON files remain the source of truth.
// Usage: node tools/build-translations.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ar = JSON.parse(readFileSync(join(root, 'translations/ar.json'), 'utf8'));
const en = JSON.parse(readFileSync(join(root, 'translations/en.json'), 'utf8'));
const banner = '/* AUTO-GENERATED by tools/build-translations.mjs — do not edit. Edit ar.json / en.json instead. */\n';
writeFileSync(join(root, 'translations/translations.bundle.js'),
  banner + 'window.RABADH_TRANSLATIONS = ' + JSON.stringify({ ar, en }) + ';\n');
console.log('translations.bundle.js written');
